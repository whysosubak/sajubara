#!/usr/bin/env node
// Parse /public/images/bara/ filenames like:
//   "1. 갑자 · wood-rat — \"새벽 풀숲, 처음 트는 발자국\".png"
// and (a) copy each to a clean path /public/images/bara/{id}.png,
// (b) emit lib/bara/cards.generated.ts with 60-entry FILLED map.
//
// The artist used "sheep" for 미(未); code uses "goat". We normalize sheep → goat for the id only.
//
// Usage: node scripts/build-bara-cards.mjs

import { readdirSync, copyFileSync, existsSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const IMG_DIR = join(__dirname, "..", "public", "images", "bara");
const OUT_TS = join(__dirname, "..", "lib", "bara", "cards.generated.ts");

const VALID_ELEMENTS = ["wood", "fire", "earth", "metal", "water"];
const VALID_BRANCHES = ["rat", "ox", "tiger", "rabbit", "dragon", "snake", "horse", "goat", "monkey", "rooster", "dog", "pig"];

// Artist uses "sheep" for 양/미. Code uses "goat". Normalize.
function normalizeBranch(branch) {
  return branch === "sheep" ? "goat" : branch;
}

function parseFilename(name) {
  // Strip .png; expect: "{num}. {ganzi_ko} · {element-branch} — \"{nickname}\""
  if (!name.endsWith(".png")) return null;
  const stem = name.slice(0, -4);
  // Pattern: <num>. <ganzi> · <id> — "<nickname>"
  const m = stem.match(/^(\d+)\.\s*(\S+)\s*·\s*([a-z]+)-([a-z]+)\s*—\s*[""](.+?)[""]$/);
  if (!m) return null;
  const [, num, ganziKo, element, branchRaw, nickname] = m;
  if (!VALID_ELEMENTS.includes(element)) return null;
  const branch = normalizeBranch(branchRaw);
  if (!VALID_BRANCHES.includes(branch)) return null;
  return {
    num: parseInt(num, 10),
    ganziKo,
    element,
    branch,
    branchRaw,
    id: `${element}-${branch}`,
    nickname,
    originalFile: name,
  };
}

function main() {
  const entries = readdirSync(IMG_DIR);
  const parsed = [];
  const skipped = [];

  for (const f of entries) {
    if (!f.endsWith(".png")) continue;
    // Skip already-clean files like "wood-rat.png" (10 chars + .png)
    if (/^[a-z]+-[a-z]+\.png$/.test(f)) continue;
    const info = parseFilename(f);
    if (!info) {
      skipped.push(f);
      continue;
    }
    parsed.push(info);
  }

  if (skipped.length) {
    console.warn(`⚠️  Skipped ${skipped.length} unparseable files:`);
    skipped.forEach((s) => console.warn("   - " + s));
  }

  if (parsed.length === 0) {
    console.error("❌ No parseable files found in " + IMG_DIR);
    process.exit(1);
  }

  parsed.sort((a, b) => a.num - b.num);
  console.log(`✓ Parsed ${parsed.length} cards`);

  // Copy each to clean path
  let copies = 0;
  for (const p of parsed) {
    const src = join(IMG_DIR, p.originalFile);
    const dst = join(IMG_DIR, `${p.id}.png`);
    if (existsSync(dst)) continue;
    copyFileSync(src, dst);
    copies++;
  }
  console.log(`✓ Copied ${copies} files to clean paths (${parsed.length - copies} already existed)`);

  // De-duplicate by id (in case two filenames map to same id, e.g. sheep & goat).
  const byId = new Map();
  for (const p of parsed) byId.set(p.id, p);

  // Emit TS
  const header = `// AUTO-GENERATED by scripts/build-bara-cards.mjs — do NOT edit by hand.
// Re-run \`node scripts/build-bara-cards.mjs\` after changing image filenames.

import type { BaraCard } from "./types";

export type BaraFillData = Partial<Pick<BaraCard, "nickname" | "body" | "motif" | "colorTone" | "image">>;

export const BARA_FILLED: Record<string, BaraFillData> = {
`;
  const lines = [];
  for (const id of Array.from(byId.keys()).sort()) {
    const p = byId.get(id);
    const safeNick = p.nickname.replace(/"/g, '\\"');
    lines.push(`  "${id}": {`);
    lines.push(`    nickname: "${safeNick}",`);
    lines.push(`    image: "/images/bara/${id}.png",`);
    lines.push(`    motif: "${p.ganziKo}",`);
    lines.push(`  },`);
  }
  const footer = `};

export const BARA_GANZI_BY_ID: Record<string, string> = {
`;
  const ganziLines = [];
  for (const id of Array.from(byId.keys()).sort()) {
    ganziLines.push(`  "${id}": "${byId.get(id).ganziKo}",`);
  }

  const out = header + lines.join("\n") + "\n" + footer + ganziLines.join("\n") + "\n};\n";
  writeFileSync(OUT_TS, out, "utf-8");
  console.log(`✓ Wrote ${OUT_TS} (${byId.size} cards)`);
}

main();
